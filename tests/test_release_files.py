"""Release files: license, notice, data card, citation, contributing note, and the README example run as written."""
import hashlib
import os
import re

import pytest

import nom

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
APACHE_2_SHA256 = "cfc7749b96f63bd31c3c42b5c471bf756814053e847c10f3eb003417bc523d30"   # apache.org/licenses/LICENSE-2.0.txt


def _read(name):
    with open(os.path.join(ROOT, name), encoding="utf-8") as f:
        return f.read()


def test_license_is_the_apache_2_text():
    with open(os.path.join(ROOT, "LICENSE"), "rb") as f:
        assert hashlib.sha256(f.read()).hexdigest() == APACHE_2_SHA256


def test_version_is_consistent():
    assert nom.__version__ == "1.0.0"
    assert re.search(r'^version = "1\.0\.0"$', _read("pyproject.toml"), re.M)
    assert re.search(r"^version: 1\.0\.0$", _read("CITATION.cff"), re.M)


def test_contributing_is_three_lines():
    lines = _read("CONTRIBUTING.md").strip().splitlines()
    assert len(lines) == 3 and "Pull requests are not accepted" in lines[1]


def test_citation_has_the_required_fields():
    cff = _read("CITATION.cff")
    for key in ("cff-version:", "message:", "title:", "authors:", "version:", "license: Apache-2.0"):
        assert key in cff


def test_minimal_dependencies():
    deps = re.search(r"dependencies = \[(.*?)\]", _read("pyproject.toml"), re.S).group(1)
    names = sorted(re.findall(r'"([A-Za-z0-9_\-]+)', deps))
    assert names == ["huggingface_hub", "numpy", "safetensors", "torch"]


@pytest.mark.skipif(not (os.path.isfile(os.path.join(ROOT, "DATA.md")) and os.path.isfile(os.path.join(ROOT, "NOTICE"))),
                    reason="DATA.md and NOTICE are generated by the export once every training source is cleared")
def test_data_card_and_notice():
    data, notice = _read("DATA.md"), _read("NOTICE")
    sections = re.findall(r"^### (.+)$", data, re.M)
    assert sections and data.startswith("# Training data")
    assert "## Synthetic data" in data
    assert all(f"- {s}:" in notice for s in sections)


def _readme_example() -> str:
    blocks = re.findall(r"```python\n(.*?)```", _read("README.md"), re.S)
    assert blocks, "README has no python example"
    return blocks[0]


def test_readme_example_runs_as_written(monkeypatch):
    """Runs the README's first python block verbatim. Weights: the published repo id, or NOM_WEIGHTS (local folder or
    repo id) while the weights are not published yet."""
    src = os.environ.get("NOM_WEIGHTS") or (os.path.join(ROOT, "weights")
                                             if os.path.isfile(os.path.join(ROOT, "weights", "model.safetensors")) else None)
    if src is None:
        pytest.skip("no weights: set NOM_WEIGHTS")
    real = nom.NomForecaster.from_pretrained.__func__
    monkeypatch.setattr(nom.NomForecaster, "from_pretrained",
                        classmethod(lambda cls, _repo_id, **kw: real(cls, src, **kw)))
    scope = {}
    exec(compile(_readme_example(), "README.md", "exec"), scope)
    assert scope["forecast"].quantiles.shape == (1, 48, 9)
